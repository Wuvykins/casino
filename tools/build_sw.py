#!/usr/bin/env python3
"""Regenerate sw.js — the offline cache list. Run after adding or changing any file:  python3 tools/build_sw.py
The version is a hash of every listed file, so the phone picks up changes on its next launch."""
import hashlib, os, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
KEEP = ('.html', '.css', '.js', '.webmanifest', '.json', '.png', '.jpg', '.jpeg', '.webp', '.mp3', '.m4a', '.wav', '.ogg')
# Songs stream from the network and stay out of the offline cache: 25+ of them is more than iOS will reliably hold in
# the Cache API, and one failed download would fail the whole install. Everything else (room loop, sfx, voices) is cached.
STREAM = lambda f: f.startswith('assets/music/song-')
# assets/manifest.json: which sound files exist, so the game doesn't have to probe for them at start-up (iPhone probes
# time out while a new build is downloading, and the game then falls back to its synth placeholders — Nic, v142).
import re as _re
def _num(f): m = _re.search(r'(\d+)', f); return int(m.group(1)) if m else 0
manifest = {
    'sfx': sorted(f for f in os.listdir('assets/sfx') if f.lower().endswith(('.mp3', '.m4a', '.wav'))),
    'music': sorted((f for f in os.listdir('assets/music') if f.lower().endswith(('.mp3', '.m4a'))), key=_num),
}
json.dump(manifest, open('assets/manifest.json', 'w'), indent=0)
files = ['index.html', 'manifest.webmanifest']
for top in ('css', 'js', 'assets'):
    for d, _, fs in os.walk(top):
        for f in fs:
            rel = os.path.join(d, f).replace(os.sep, '/')
            if f.lower().endswith(KEEP) and not STREAM(rel):
                files.append(rel)
files = sorted(set(files))
h = hashlib.sha1()
for f in files:
    h.update(f.encode()); h.update(open(f, 'rb').read())
version = h.hexdigest()[:10]
sw = f"""// Generated by tools/build_sw.py — do not edit by hand. Version {version}, {len(files)} files.
const VERSION = 'casino-{version}';
const FILES = {json.dumps(files)};
self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(FILES.map((f) => new Request(f, {{ cache: 'reload' }})))).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});
// Cached files come straight from the cache (fast, works offline). Anything else goes to the network,
// and a successful same-origin answer is kept so optional art you add later works offline too.
self.addEventListener('fetch', (e) => {{
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET' || u.origin !== self.location.origin) return;
  if (/\/assets\/music\/song-/.test(u.pathname)) return;   // songs stream (range requests) and are not cached
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || fetch(e.request).then((res) => {{
    if (res.ok && res.status === 200) {{ const copy = res.clone(); caches.open(VERSION).then((c) => c.put(e.request, copy)); }}
    return res;
  }})));
}});
"""
open('sw.js', 'w').write(sw)
total = sum(os.path.getsize(f) for f in files)
import re
build = re.search(r"VERSION = '(v\d+)'", open('js/version.js').read())
print(f'sw.js written: version {version}, {len(files)} files, {total/1e6:.1f} MB cached offline — js/version.js says {build.group(1) if build else "?"} (bump it before zipping)')
